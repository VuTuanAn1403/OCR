"""Plain-text companion for the Markdown subset emitted by this project.

Keep visible words, numeric literals, code and formula bodies. Formatting and
asset targets are removed; no spelling correction or Unicode normalization is
performed. This is not a parser for arbitrary third-party Markdown documents.
"""
import html
import re

_SEPARATOR = re.compile(r"^\s*:?-{3,}:?\s*$")
_RULE = re.compile(r"^\s*(?:-{3,}|_{3,}|(?:\*\s*){3,})\s*$")
_FENCE = re.compile(r"^\s*(`{3,}|~{3,})(.*)$")
_ESCAPE = re.compile(r"\\([\\`*{}\[\]()#+\-.!_>|])")
_LINK = re.compile(r"!?\[([^\]\n]*(?:\\\][^\]\n]*)*)\]\((?:\\.|[^()\n]|\([^()\n]*\))*\)")
_STRONG = re.compile(r"(?<![\w\\])([*_]{2})(?=\S)(.+?)(?<=\S)\1(?!\w)")
_EMPHASIS = re.compile(r"(?<![\w\\])([*_])(?=\S)(.+?)(?<=\S)\1(?!\w)")


def _inline(text):
    text = _LINK.sub(lambda match: match.group(1), text)
    text = re.sub(r"(?<!\\)(`+)(.+?)\1", lambda match: match.group(2), text)
    text = _STRONG.sub(lambda match: match.group(2), text)
    text = _EMPHASIS.sub(lambda match: match.group(2), text)
    text = re.sub(r"<br\s*/?>", "\n", text, flags=re.IGNORECASE)
    # Only structural tags generated by table rendering are formatting. Do
    # not drop arbitrary angle-bracket text or mathematical inequalities.
    text = re.sub(r"</?(?:table|thead|tbody|tfoot|tr|td|th|caption)\b[^>]*>", "", text, flags=re.IGNORECASE)
    return html.unescape(_ESCAPE.sub(lambda match: match.group(1), text))


def markdown_plain_text(markdown):
    """Render final result.md as UTF-8-ready text, using tabs between table cells."""
    result, fence, math_block = [], None, None
    for line in markdown.splitlines():
        if math_block is not None:
            if line.strip() == math_block:
                math_block = None
            else:
                result.append(line)
            continue
        marker = _FENCE.match(line)
        if fence is not None:
            if marker and marker.group(1)[0] == fence[0] and len(marker.group(1)) >= len(fence) and not marker.group(2).strip():
                fence = None
            else:
                result.append(line)  # code/formula text is literal
            continue
        if marker:
            fence = marker.group(1)
            continue
        if line.strip() in ("$$", r"\["):
            math_block = "$$" if line.strip() == "$$" else r"\]"
            continue
        if _RULE.fullmatch(line):
            continue
        if re.fullmatch(r"\s*<!--.*?-->\s*", line):
            continue
        # Split before unescaping so a literal \| cannot create another cell.
        if line.lstrip().startswith("|") and line.rstrip().endswith("|"):
            cells = re.split(r"(?<!\\)\|", line.strip())[1:-1]
            if cells and all(_SEPARATOR.fullmatch(cell) for cell in cells):
                continue
            result.append("\t".join(_inline(cell.strip()) for cell in cells))
            continue
        line = re.sub(r"^\s{0,3}#{1,6}\s+", "", line)
        line = re.sub(r"^(?:\s{0,3}>\s?)+", "", line)
        line = re.sub(r"^\s{0,3}[-+*]\s+", "", line)
        result.append(_inline(line))
    # Keep line/cell boundaries and collapse only repeated empty layout lines.
    return re.sub(r"\n{3,}", "\n\n", "\n".join(result)).strip("\n") + "\n"
